package com.dsbuilder.ds.components.domain

import java.util.UUID

/**
 * Признак поддержки состояний свойства: состояния, в которых генератор платформы выражает значение, и допустимость
 * их сочетаний. Пустой [stateIds] значит, что значения по состояниям свойство не принимает. Незаданный признак
 * (`null` там, где он хранится) — мета его ещё не сообщила.
 */
data class PropertyStateSupport(
    /** Допустимые состояния в порядке словаря состояний. */
    val stateIds: List<UUID>,
    /** Допускается ли набор из нескольких состояний. */
    val combinations: Boolean,
)
