import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

import { generateThemes } from './generate-theme.ts';
import { CORE_VERSION, cliDirectory, writePackagePart } from './package-output.ts';
import { readThemeSetSource } from './theme-source.ts';
import { resolveLocalThemes } from './local-theme-source.ts';

/**
 * Генерирует темы дизайн-системы из .sdds, без компонентов: все темы из `tenants` или одну с `--tenant`.
 * Без `--package` в `output` заменяется только `src/theme`; с `--package` в `output` пишется папка пакета
 * без сборки, в котором есть только тема, без компонентов. Компоненты генерирует `generate:components`. К бэкенду CLI не обращается.
 */
async function main() {
    const { values } = parseArgs({
        options: {
            sdds: { type: 'string', default: join(cliDirectory, '.sdds') },
            tenant: { type: 'string' },
            'default-tenant': { type: 'string' },
            out: { type: 'string', default: join(cliDirectory, 'output') },
            name: { type: 'string' },
            'ds-version': { type: 'string', default: '0.1.0' },
            'core-version': { type: 'string', default: CORE_VERSION },
            package: { type: 'boolean', default: false },
            help: { type: 'boolean', short: 'h' },
        },
    });

    if (values.help) {
        console.log(`Generate the theme of a local React design system package.

Usage: npm run generate:theme -- [options]
  --sdds <directory>       Local data directory (default: js/cli/.sdds)
  --tenant <name>          Generate one theme: a tenant name from .sdds/config.json, otherwise
                           a directory name in .sdds/tenants (default: every theme)
  --default-tenant <name>  Theme whose values become the fallbacks in tokens (default: the first
                           generated theme by directory name); looked up like --tenant
  --out <directory>        Output directory (default: js/cli/output)
  --name <name>            Package name; required with --package
  --ds-version <version>   Package version (default: 0.1.0)
  --core-version <version> Plasma core version (default: ${CORE_VERSION})
  --package                Write the whole theme-only package (package.json, build configs, src), not built

Typography media queries follow "breakpoints" in .sdds/config.json when it is set: screens from narrow to wide,
e.g. [{"name":"screenS","to":959},{"name":"screenM","from":960,"to":1280},{"name":"screenL","from":1281}]
("from" is min-width, "to" is max-width); only the listed screens are generated.
Reads every theme directory with meta.json in .sdds/tenants and the palette; config.json is optional.
Replaces only src/theme (and src/index.ts) in the output directory; with --package writes the package
files and replaces src. Build it with npm install && npm run build, pack it with npm pack. Components are generated by generate:components.`);
        return;
    }

    const source = await readThemeSetSource(
        await resolveLocalThemes(resolve(values.sdds), {
            tenant: values.tenant,
            defaultTenant: values['default-tenant'],
        }),
    );

    const result = await writePackagePart({
        parts: ['theme'],
        outputDirectory: resolve(values.out),
        packageName: values.name,
        packageVersion: values['ds-version'],
        coreVersion: values['core-version'],
        pack: values.package,
        fill: (pathToDir) => generateThemes(source, join(pathToDir, 'src', 'theme')),
    });
    console.log(`Generated ${result}`);
}

main().catch((error) => {
    console.error('Failed to generate theme:', error);
    process.exitCode = 1;
});
