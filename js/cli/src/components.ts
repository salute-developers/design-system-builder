import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

import { COMPONENTS_PACKAGE, readComponentsForGeneration } from './components-input.ts';
import { generateComponentsFiles } from './generator/generate.ts';
import { CORE_VERSION, cliDirectory, writePackagePart } from './package-output.ts';

/**
 * Генерирует компоненты дизайн-системы из выгрузки в .sdds, без темы.
 * Без `--package` в `output` заменяется только `src/components`; с `--package` собирается пакет
 * из одних компонентов. Тему генерирует `generate:theme`. К бэкенду CLI не обращается.
 */
async function main() {
    const { values } = parseArgs({
        options: {
            sdds: { type: 'string', default: join(cliDirectory, '.sdds') },
            components: { type: 'string' },
            web: { type: 'string' },
            out: { type: 'string', default: join(cliDirectory, 'output') },
            name: { type: 'string' },
            'ds-version': { type: 'string', default: '0.1.0' },
            'core-version': { type: 'string', default: CORE_VERSION },
            package: { type: 'boolean', default: false },
            help: { type: 'boolean', short: 'h' },
        },
    });

    if (values.help) {
        console.log(`Generate the components of a local React design system package.

Usage: npm run generate:components -- [options]
  --sdds <directory>       Local data directory (default: js/cli/.sdds)
  --components <directory> Fetched components (default: <sdds>/components)
  --web <directory>        Web data: web-adapter.json (default: <sdds>/web)
  --out <directory>        Output directory (default: js/cli/output)
  --name <name>            Package name; required with --package
  --ds-version <version>   Package version (default: 0.1.0)
  --core-version <version> Plasma core version (default: ${CORE_VERSION})
  --package                Build a components-only package and write a .tgz instead of the sources

Reads meta.json and component configs from the components directory and web-adapter.json
(components fetch for react) from the web directory. Web token mappings are built on every run
from ${COMPONENTS_PACKAGE} installed in js/cli, like generate:api-meta does.
Replaces only src/components (and src/index.ts) in the output directory, or writes
<scope>-<name>-<version>-components.tgz with --package. The theme is generated by generate:theme.`);
        return;
    }

    const sddsDirectory = resolve(values.sdds);
    const componentsMeta = await readComponentsForGeneration({
        sddsDirectory,
        components: values.components,
        web: values.web,
    });

    const result = await writePackagePart({
        parts: ['components'],
        outputDirectory: resolve(values.out),
        packageName: values.name,
        packageVersion: values['ds-version'],
        coreVersion: values['core-version'],
        pack: values.package,
        fill: (pathToDir) => generateComponentsFiles({ pathToDir, componentsMeta }),
    });
    console.log(`Generated ${result}`);
}

main().catch((error) => {
    console.error('Failed to generate components:', error);
    process.exitCode = 1;
});
